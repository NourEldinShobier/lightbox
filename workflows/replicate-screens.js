export const meta = {
  name: 'replicate-screens',
  description: 'Replicate a folder of UI screenshots as pixel-accurate HTML/CSS in parallel, run a surface pass on borders, shadows and backgrounds, and build one page with each original beside its replica',
  whenToUse: 'Several screenshots to rebuild as HTML/CSS. args: { dir: "<absolute folder>", images?: ["a.png", ...], groupSize?: 3, surfacePass?: true, title?: "..." }',
  phases: [
    { title: 'Inventory', detail: 'list images, drop duplicates, fix extensionless files' },
    { title: 'Build', detail: 'one agent per group of screenshots' },
    { title: 'Refine', detail: 'surface pass: fills, 1px strokes, shadows, radii' },
    { title: 'Assemble', detail: 'side-by-side gallery and load check' },
  ],
}

const A = typeof args === 'string' ? { dir: args } : (args || {})
if (!A.dir) throw new Error('Pass args: { dir: "<absolute path of the screenshot folder>" }')
const SEP = A.dir.includes('\\') ? '\\' : '/'
const DIR = A.dir.replace(/[\\/]+$/, '')
const PARTS = A.out || `${DIR}${SEP}parts`
const GROUP = Math.max(1, A.groupSize || 3)
const SURFACE = A.surfacePass !== false
const TITLE = A.title || 'Replicas'
const isAbs = p => /^([a-zA-Z]:[\\/]|\/|\\\\)/.test(p)

// Prefer the plugin's agent definition; fall back to a general agent with the same brief.
async function run(prompt, opts) {
  try {
    return await agent(prompt, { ...opts, agentType: 'lightbox:screen-replicator' })
  } catch (e) {
    if (!/agent ?type|not found|unknown/i.test(String(e))) throw e
    log(`agent type lightbox:screen-replicator unavailable; using a general agent`)
    return agent(prompt, opts)
  }
}

phase('Inventory')
let images = A.images
if (!images || !images.length) {
  const inv = await agent(
    `List the screenshots to replicate in "${DIR}". Run: lightbox images "${DIR}" --fix-ext "${DIR}${SEP}refs" --json
(the lightbox CLI is on PATH via the lightbox plugin; if the command is missing, run its doctor/setup first: lightbox doctor, lightbox setup).
Return every image's absolute path from that JSON, excluding entries whose duplicate_of is set, files under "${PARTS}", and pages or renders previously generated by this workflow (replicas*.html, *_side.png, *_diff.png). Extensionless files were copied to refs/ with an extension: use those copies.`,
    { label: 'inventory', phase: 'Inventory', schema: { type: 'object', required: ['files'], properties: { files: { type: 'array', items: { type: 'string' } } } } },
  )
  images = (inv && inv.files) || []
}
images = images.map(f => (isAbs(f) ? f : `${DIR}${SEP}${f}`))
if (!images.length) throw new Error(`No images found in ${DIR}`)

const keyName = i => { let s = ''; for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s; return s }
const groups = []
for (let i = 0; i < images.length; i += GROUP) groups.push({ key: keyName(groups.length), files: images.slice(i, i + GROUP) })
log(`${images.length} screenshots in ${groups.length} groups of up to ${GROUP}`)

const contract = (g) => `Output: ONE HTML fragment file "${PARTS}${SEP}${g.key}.html" (create the folder if needed):
<section class="sec-${g.key}">
  <style> every selector prefixed with .sec-${g.key} </style>
  ${g.files.map((_, i) => `<figure class="card" id="${g.key}${i + 1}"><figcaption>short title</figcaption><div class="stage">...</div></figure>`).join('\n  ')}
</section>
Each .stage is exactly 800px wide with height = round(800 * refH / refW), position:relative; overflow:hidden. No global selectors (body, html, bare figure). Pure HTML/CSS with inline SVG icons; no images of the reference.
References, in figure order:
${g.files.map((f, i) => `  ${g.key}${i + 1}: ${f}`).join('\n')}
Keep scratch files (harness pages, renders, diffs) in a subfolder scratch_${g.key} of your session scratchpad directory (or of the system temp folder if you have none), never in "${DIR}"; write only the fragment there.`

const buildPrompt = g => `Replicate these UI screenshots as pixel-accurate HTML/CSS. Load the lightbox:replicate-screen skill with the Skill tool and follow it (measure with lightbox sample/zoom, never guess colours; render + diff each screen for at least 3 rounds).
Pay close attention to the dark mood, exact surface colours, 1px borders and inner highlights, shadows, radii and text.
${contract(g)}
Final reply: one line per screen with id, file, final mean_abs_diff, rounds run, and the largest remaining mismatch.`

const refinePrompt = (g, prev) => `Surface pass on an existing replica. Previous report (do not trust it; measure first): ${String(prev || '').slice(0, 700)}
Load the lightbox:replicate-screen skill and follow its "Surface pass" section: for EVERY surface in every screen (window frame, title bar, panes, cards, rows, buttons, inputs, flyouts, menus, taskbar, dividers) sample fill, each edge's stroke and inner highlight, the 0-40px shadow profile and the radius in both reference and render (lightbox sample --vs), and fix the CSS until each is within ~3 per RGB channel. Edit the fragment surgically; keep ids, scoping and text/icons.
${contract(g)}
Final reply: one line per screen with id, mean_abs_diff before -> after, and the largest remaining surface mismatch (surface, reference vs render colour).`

const stages = [g => run(buildPrompt(g), { label: `build:${g.key}`, phase: 'Build' })]
if (SURFACE) stages.push((built, g) => run(refinePrompt(g, built), { label: `refine:${g.key}`, phase: 'Refine' }))
const reports = await pipeline(groups, ...stages)

phase('Assemble')
const refs = {}
groups.forEach(g => g.files.forEach((f, i) => { refs[`${g.key}${i + 1}`] = f }))
const assembled = await agent(
  `Combine replica fragments into one comparison page.
1. Write this JSON to "${PARTS}${SEP}refs.json": ${JSON.stringify(refs)}
2. Run: lightbox gallery --parts "${PARTS}" --refs "${PARTS}${SEP}refs.json" --out "${DIR}${SEP}replicas.html" --title "${TITLE.replace(/"/g, '')}"
3. Check it: every figure id in refs.json has a parts fragment (report missing ones), the gallery printed no warnings, and a full-page render opens: lightbox render "${DIR}${SEP}replicas.html" <scratchpad or temp folder>/gallery.png --size 1760x1000 --full-page. Look at a downscaled view of the render to confirm replicas sit beside originals.
Return the page path, the figure count, and any problem found.`,
  { label: 'assemble', phase: 'Assemble' },
)

return { page: `${DIR}${SEP}replicas.html`, groups: groups.map((g, i) => ({ key: g.key, files: g.files, report: reports[i] })), assembled }
